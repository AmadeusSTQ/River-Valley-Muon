import distributed


def parse_args(base_parser, args, namespace):
    parser = base_parser
    # General training params
    parser.add_argument("--experiment-name", default=None, type=str)
    parser.add_argument("--seed", default=0, type=int)
    parser.add_argument(
        "--data-seed",
        default=1337,
        type=int,
        help="Legacy default for both training and evaluation data seeds.",
    )
    parser.add_argument(
        "--train-data-seed",
        default=None,
        type=int,
        help="Seed for training-data order. Defaults to --data-seed.",
    )
    parser.add_argument(
        "--eval-data-seed",
        default=None,
        type=int,
        help="Seed for evaluation-data order. Defaults to --data-seed.",
    )
    parser.add_argument("--eval-interval", default=200, type=int)
    parser.add_argument("--full-eval-at", nargs="+", type=int)
    parser.add_argument("--eval-batches", default=32, type=int)
    parser.add_argument("--device", default="cuda:0", type=str)
    parser.add_argument(
        "--distributed-backend",
        default=None,
        type=str,
        required=False,
        choices=distributed.registered_backends(),
    )
    parser.add_argument("--log-interval", default=50, type=int)

    # Checkpointing
    parser.add_argument("--results-base-folder", default="./exps", type=str)
    parser.add_argument("--permanent-ckpt-interval", default=0, type=int)
    parser.add_argument("--permanent-ckpt-at", nargs="+", type=int)
    parser.add_argument("--latest-ckpt-interval", default=0, type=int)
    parser.add_argument("--resume-from", default=None, type=str)
    parser.add_argument("--resume-from-swa", default=None, type=str)

    parser.add_argument("--auto-resume", default=True)
    parser.add_argument("--load-optimizer-state", action="store_true")
    parser.add_argument("--load-scheduler-state", action="store_true")
    parser.add_argument("--second-warmup-steps", default=100, type=int)
    parser.add_argument(
    "--transfer-momentum",
    default="none",
    choices=["none", "muon_to_adamw", "muon_to_sgd"],
    type=str,
)

    parser.add_argument(
        "--momentum-source-ckpt",
        default=None,
        type=str,
        help="Checkpoint directory to load source optimizer momentum from. "
            "If None, use --resume-from.",
    )

    parser.add_argument(
    "--adamw-exp-avg-init",
    default="muon_momentum",
    choices=["muon_momentum", "update_space_muon"],
    type=str,
    )

    parser.add_argument(
        "--adamw-update-blend-alpha",
        default=0.8,
        type=float,
        help="Blend weight for Muon update-space direction when initializing AdamW exp_avg.",
    )

    parser.add_argument(
        "--adamw-muon-v-scale",
        default=0.01,
        type=float,
        help="Scale for Muon momentum squared fallback in AdamW exp_avg_sq warm start.",
    )

    parser.add_argument(
        "--adamw-transfer-step-init",
        default="source_itr",
        choices=["source_itr", "zero", "calib_batches"],
        type=str,
    )


    parser.add_argument(
        "--adamw-exp-avg-sq-init",
        default="momentum_sq",
        choices=["zeros", "momentum_sq", "grad_sq_calib", "max_grad_sq_muon_sq"],
        type=str,
        help="How to initialize AdamW exp_avg_sq when transferring Muon momentum.",
    )
    
    parser.add_argument(
    "--adamw-v-calib-batches",
    default=32,
    type=int,
    help="Number of batches used to estimate AdamW exp_avg_sq at Muon -> AdamW switch.",
    )

    parser.add_argument(
        "--adamw-v-calib-scale",
        default=1.0,
        type=float,
        help="Scale applied to calibrated gradient-square estimate.",
    )

    parser.add_argument(
        "--adamw-v-floor",
        default=1e-12,
        type=float,
        help="Relative floor for calibrated AdamW exp_avg_sq.",
    )
    
    

    parser.add_argument(
        "--adamw-exp-avg-sq-scale",
        default=1.0,
        type=float,
        help="Scale applied to AdamW exp_avg_sq when initializing it from Muon momentum.",
    )

    parser.add_argument(
        "--momentum-transfer-scale",
        default=1.0,
        type=float,
        help="Scale applied to transferred Muon momentum.",
    )

    # logging params (WandB)
    parser.add_argument("--wandb", action="store_true")  # whether to use wandb or not
    parser.add_argument("--wandb-project", default="my-project", type=str)
    parser.add_argument(
        "--wandb-run-prefix", default="none", type=str
    )  # is added before the autogenerated experiment name
    parser.add_argument(
        "--eval-seq-prefix", default="none", type=str
    )  # prefix used to generate sequences
    parser.add_argument("--log-dynamics", action="store_true")
    parser.add_argument(
        "--dynamics-logger-cfg", default="./src/logger/rotational_logger.yaml", type=str
    )

    # Schedule
    parser.add_argument(
        "--scheduler",
        default="cos",
        choices=["linear", "cos", "wsd", "none", "cos_inf"],
    )
    parser.add_argument("--cos-inf-steps", default=0, type=int)
    # parser.add_argument("--cos-final-lr", default=1e-6, type=float)
    parser.add_argument("--iterations", default=15000, type=int)
    parser.add_argument("--warmup-steps", default=300, type=int)
    parser.add_argument("--lr", default=1e-3, type=float)
    # wsd
    parser.add_argument("--wsd-final-lr-scale", default=0.0, type=float)
    parser.add_argument("--wsd-fract-decay", default=0.2, type=float)
    # parser.add_argument("--wsd-exponential-decay", action="store_true")
    parser.add_argument(
        "--decay-type",
        default="linear",
        choices=["linear", "cosine", "exp", "miror_cosine", "square", "sqrt"],
    )
    # Optimization
    parser.add_argument(
    "--opt",
    default="adamw",
    choices=["adamw", "sgd", "SFAdamW", "muon", "muon_gd_ada"]
)    
    parser.add_argument("--batch-size", default=50, type=int)
    parser.add_argument("--acc-steps", default=4, type=int)
    parser.add_argument("--weight-decay", default=1e-1, type=float)
    parser.add_argument("--beta1", default=0.9, type=float)
    parser.add_argument("--beta2", default=0.95, type=float)
    parser.add_argument(
        "--grad-clip", default=1.0, type=float
    )  # default value is 1.0 in NanoGPT

    # Muon-GD-Ada params
    parser.add_argument("--gd-lr", default=None, type=float)
    parser.add_argument("--gd-momentum", default=0.0, type=float)
    parser.add_argument("--muon-gd-momentum", default=0.95, type=float)
    parser.add_argument("--psi", default=1.0, type=float)
    parser.add_argument("--adapt-interval", default=100, type=int)
    parser.add_argument("--muon-gd-warmup-steps", default=0, type=int)
    parser.add_argument("--psi-up", default=2.0, type=float)
    parser.add_argument("--psi-down", default=0.5, type=float)
    parser.add_argument("--initial-mode", default="muon", choices=["muon", "gd"])
    parser.add_argument("--ns-steps", default=5, type=int)
    parser.add_argument("--rank-tol", default=1e-7, type=float)

    # Weight Averaging
    parser.add_argument("--weight-average", action="store_true")
    parser.add_argument(
        "--wa-interval",
        default=5,
        type=int,
        help="How often to take the average (every k steps). Must divide wa-horizon.",
    )
    parser.add_argument(
        "--wa-horizon",
        default=500,
        type=int,
        help="How frequently we save uniform model averages. Should divide "
        + "latest-ckpt-interval, otherwise some points may not be saved "
        + "correctly.",
    )
    parser.add_argument(
        "--wa-dtype",
        default="float32",
        type=str,
        choices=["float32", "float64"],
    )

    parser.add_argument("--wa-use-temp-dir", action="store_true")
    parser.add_argument("--wa-sweep-horizon", action="store_true")
    parser.add_argument("--max-num-wa-sweeps", default=5, type=int)

    parser.add_argument("--exponential-moving-average", action="store_true")
    parser.add_argument(
        "--ema-interval",
        default=10,
        type=int,
        help="How often to take the EMA average (every k steps).",
    )
    parser.add_argument(
        "--ema-decay",
        default=0.95,
        type=float,
        help="EMA decay parameter (between 0.9 and 1).",
    )
    parser.add_argument(
        "--ema-after-warmup",
        action="store_true",
        help="Start EMA after warmup steps.",
    )

    # Dataset params
    parser.add_argument("--datasets-dir", type=str, default="./datasets/")
    parser.add_argument(
        "--dataset",
        default="slimpajama",
        choices=[
            "wikitext",
            "shakespeare-char",
            "hongloumeng-char",
            "tangshi300-char",
            "tinystories",
            "tinypython-1m",
            "arxiv",
            "arxiv2000",
            "arxiv+wiki",
            "openwebtext2",
            "redpajama",
            "redpajama1b",
            "slimpajama",
            "slimpajama_chunk1",
            "redpajamav2",
        ],
    )
    parser.add_argument(
        "--tokenizer", default="gpt2", type=str, choices=["gpt2", "mistral"]
    )
    parser.add_argument("--vocab-size", default=50304, type=int)
    parser.add_argument(
        "--data-in-ram", action="store_true"
    )  # force the data to RAM, mostly useless except for openwebtext2

    # Model params
    parser.add_argument(
        "--model",
        default="llama",
        choices=[
            "base",
            "llama",
        ],
    )
    parser.add_argument("--parallel-block", action="store_true")
    parser.add_argument(
        "--use-pretrained", default="none", type=str
    )  # 'none', 'gpt-2' or a path to the pretraind model
    parser.add_argument("--from-dense", action="store_true")
    parser.add_argument("--init-std", default=0.02, type=float)
    parser.add_argument("--dropout", default=0.0, type=float)
    parser.add_argument("--n-head", default=12, type=int)
    parser.add_argument("--n-layer", default=24, type=int)  # depths in att + ff blocks
    parser.add_argument("--sequence-length", default=512, type=int)
    parser.add_argument(
        "--n-embd", default=768, type=int  # embedding size / hidden size ...
    )
    parser.add_argument(
        "--multiple-of",  # make SwiGLU hidden layer size multiple of large power of 2
        default=256,
        type=int,
    )
    parser.add_argument("--rmsnorm-eps", default=1e-5, type=float)
    parser.add_argument(
        "--dtype",
        default="bfloat16",
        type=str,
        choices=["float32", "float16", "bfloat16"],
    )
    parser.add_argument("--bias", default=False, type=bool)
    parser.add_argument("--compile", action="store_true")
    parser.add_argument("--mlp-dim-exp-factor", default=1.0, type=float)
    return parser.parse_args(args, namespace)
